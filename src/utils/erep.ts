/**
 * EREP (IFCEREP) report helpers — canned JCL builder and output parser for
 * LOGREC analysis. The tool submits the report job (a read, but it still
 * consumes batch capacity, so it is a governed write) and summarizes the
 * EREP SUMMARY output.
 */

/** Build a canned EREP summary job for a LOGREC dataset. */
export function buildErepJcl(logrecDataset: string, report: 'SUMMARY' | 'HISTORY' = 'SUMMARY'): string {
  const controls =
    report === 'HISTORY'
      ? 'REPORT=HISTORY,HISTOPT=ALL\nEND'
      : 'REPORT=SUMMARY\nEND';
  return [
    '//MCPSMLOG JOB (MCP,LOGREC),MSGCLASS=X,CLASS=A',
    '//* Auto-generated by mainframe-mcp-server (analyze_logrec)',
    `//EREP EXEC PGM=IFCEREP,PARM='CARD',REGION=4M`,
    `//EREPDD  DD DISP=SHR,DSN=${logrecDataset.toUpperCase()}`,
    '//SYSUDUMP DD SYSOUT=*',
    '//SYSOUT   DD SYSOUT=*',
    '//SYSIN    DD *',
    controls,
    '/*',
    '//',
  ].join('\n');
}

export interface ErepSummary {
  /** Record-type counts discovered in the summary (e.g. "TEMP ERRORS: 12"). */
  recordCounts: { label: string; count: number }[];
  /** Distinct abend codes seen in summary records. */
  abendCodes: string[];
  /** Distinct failing modules/CPUs mentioned. */
  entries: string[];
  /** First diagnostic lines (capped). */
  keyLines: string[];
  /** Total LOGREC records reported, when derivable. */
  totalRecords?: number;
}

/**
 * Parse the essentials out of an EREP SUMMARY report. EREP output varies by
 * release; the parser targets the stable record-type summary tables.
 */
export function parseErepSummary(text: string): ErepSummary {
  const recordCounts: { label: string; count: number }[] = [];
  const abendCodes = new Set<string>();
  const entries = new Set<string>();
  const keyLines: string[] = [];

  const countPatterns: RegExp[] = [
    /([A-Z][A-Z ]{3,28})\s{2,}(\d{1,8})\s*$/gm, // "TEMP ERRORS            12"
    /^\s*([A-Z][A-Z /()-]{3,30}?)\s+(\d{1,8})\s*$/gm,
  ];
  const exclude = /^(?:REPORT|END|PAGE|EREP|IFC|DATE|TIME|LOGREC|SUMMARY|TYPE|EOD)/i;

  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    if (keyLines.length < 15 && /ERROR|ABEND|PERM|TEMP|INTV|DEGRADED|LOST/i.test(trimmed) && !exclude.test(trimmed)) {
      keyLines.push(trimmed);
    }
    for (const m of trimmed.matchAll(/\bS[0-9A-F]{3}\b/g)) abendCodes.add(m[0]);
    const module = trimmed.match(/\b(?:MOD(?:ULE)?|EP)\s*=\s*([A-Z0-9#$@]{2,8})\b/i);
    if (module) entries.add(module[1].toUpperCase());
    const cpu = trimmed.match(/\bCPU\s*(?:SER|ID)?\s*[=:]?\s*([0-9A-F]{6})\b/i);
    if (cpu) entries.add(`CPU ${cpu[1].toUpperCase()}`);
  }

  // Record-count tables: only trust lines where the label is left of a
  // right-aligned number and the label is not a header.
  for (const pattern of countPatterns) {
    for (const m of text.matchAll(pattern)) {
      const label = m[1].trim();
      if (label.length < 4 || exclude.test(label)) continue;
      const count = Number(m[2]);
      if (!Number.isFinite(count) || count === 0) continue;
      if (recordCounts.some((r) => r.label === label)) continue;
      recordCounts.push({ label, count });
    }
  }
  recordCounts.sort((a, b) => b.count - a.count);
  const totalRecords = recordCounts.reduce((acc, r) => acc + r.count, 0);

  return {
    recordCounts: recordCounts.slice(0, 15),
    abendCodes: [...abendCodes].sort(),
    entries: [...entries].sort().slice(0, 15),
    keyLines,
    ...(totalRecords > 0 ? { totalRecords } : {}),
  };
}
